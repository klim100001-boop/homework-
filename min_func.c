#include "min_func.h"

int find_last_min(FILE *f)
{
    double prev, curr, next;
    int count = 1;   /* Счетчик длины текущей группы одинаковых чисел */
    int ans = 0;     /* Здесь храним ответ (длину последнего минимума) */

    /* Пробуем прочитать самое первое число */
    if (fscanf(f, "%lf", &curr) != 1)
    {
        return 0; /* Если файл пустой, возвращаем 0 */
    }
    
    prev = curr; /* Изначально предыдущее равно текущему */

    /* Читаем остальные числа по одному до конца файла */
    while (fscanf(f, "%lf", &next) == 1)
    {
        if (next == curr)
        {
            /* Если числа одинаковые, увеличиваем длину группы */
            count = count + 1;
        }
        else
        {
            /* Числа разные. Проверяем, было ли число curr локальным минимумом */
            /* Условие: слева больше И справа больше */
            if (prev > curr && next > curr)
            {
                ans = count; /* Запоминаем длину этой группы */
            }
            
            /* Сдвигаем переменные для следующего шага */
            prev = curr;
            curr = next;
            count = 1; /* Новая группа начинается с 1 */
        }
    }

    /* Возвращаем ответ. Если минимумов не было, вернется 0 */
    return ans;
}