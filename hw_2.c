#include <stdio.h>

int main(void) {
    int n;
    printf("Введите количество элементов последовательности: ");
    scanf("%d", &n); // Количество элементов всегда целое число!

    if (n < 3) {
        printf("Для поиска локального минимума нужно хотя бы 3 элемента.\n");
        return 0;
    }

    double first;
    printf("Введите элементы последовательности (можно с плавающей точкой):\n");
    scanf("%lf", &first); // %lf используется для считывания double

    // Переменные для отслеживания групп одинаковых вещественных чисел
    double curr_val = first; // Значение текущей группы чисел
    int curr_len = 1;        // Длина группы — всегда целое число
    double prev_val = 0.0;   // Значение предыдущей группы
    int has_prev = 0;        // Флаг существования предыдущей группы (0 или 1)

    int last_min_len = 0;    // Ответ (длина последнего минимума) — целое число

    for (int i = 2; i <= n; i++) {
        double x;
        scanf("%lf", &x); // Считываем очередное вещественное число

        if (x == curr_val) {
            curr_len++;
        } else {
            // Проверяем «впадину»: предыдущее больше текущего И новое больше текущего
            if (has_prev == 1 && prev_val > curr_val && x > curr_val) {
                last_min_len = curr_len;
            }

            prev_val = curr_val;
            has_prev = 1;
            curr_val = x;
            curr_len = 1;
        }
    }

    if (last_min_len > 0) {
        printf("Количество элементов в последнем локальном минимуме: %d\n", last_min_len);
    } else {
        printf("Локальных минимумов в последовательности не найдено.\n");
    }

    return 0;
}
